import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/estel/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright');
const browser = await chromium.launch({ executablePath:'C:/Users/ignac/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe', headless:true });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
try {
  const page = await browser.newPage({ viewport:{ width:1440, height:1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const scroll = async top => {
    await page.evaluate(top => scrollTo({ top, behavior:'instant' }), top);
    await page.waitForTimeout(100);
  };
  await page.goto('http://localhost:4321/castas/', { waitUntil:'networkidle' });
  const photo = page.locator('.framer-1qskmgv').filter({ visible:true });
  const before = await photo.boundingBox();
  await page.locator('.framer-1y163dm').filter({ visible:true }).hover();
  await page.waitForTimeout(1000);
  const after = await photo.boundingBox();
  assert(Math.abs(after.width / before.width - 1.1) < .01, 'Hero hover should enlarge the image by 10%');
  assert(await page.locator('.framer-1be2uri').first().evaluate(el => getComputedStyle(el).transform === 'matrix(1, 0, 0, 1, 0, 0)'), 'Hero underline did not expand');
  await page.mouse.move(0,0);
  await scroll(750);
  await page.waitForTimeout(700);
  await page.screenshot({ path:'scripts/castas-motion-entry.jpg', quality:85 });
  const entry = page.locator('.framer-xekszl');
  assert(await entry.evaluate(el => Math.abs(el.getBoundingClientRect().x - 582.857) < 2), 'Entry steps do not follow scroll');
  const exit = page.locator('.framer-p1klyu');
  const exitY = await exit.evaluate(el => el.getBoundingClientRect().top + scrollY);
  await scroll(exitY - 800);
  const exitBefore = await exit.evaluate(el => el.getBoundingClientRect().x);
  await scroll(exitY - 400);
  const exitAfter = await exit.evaluate(el => el.getBoundingClientRect().x);
  assert(exitBefore < exitAfter && exitAfter <= 0, 'Exit steps do not advance from the left');
  const firstRow = page.locator('#services [data-framer-name="Service"]').first();
  const firstY = await firstRow.evaluate(el => el.getBoundingClientRect().top + scrollY);
  const content = firstRow.locator('[data-framer-name="Content"]').filter({ visible:true });
  await scroll(firstY - 600);
  const initialX = await content.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
  await scroll(firstY - 400);
  const middleX = await content.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
  await scroll(firstY - 300);
  const finalX = await content.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
  assert(initialX === -150 && middleX > initialX && middleX < 0 && finalX === 0, 'Service movement is not progressive');
  await scroll(firstY - 600);
  assert(await content.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41) === -150, 'Service movement does not reverse');
  await scroll(firstY - 350);
  await page.waitForTimeout(500);
  await page.screenshot({ path:'scripts/castas-motion-services.jpg', quality:85 });
  const images = await page.locator('#services img').evaluateAll(els => els.map(el => ({ src:el.src, width:el.naturalWidth })));
  assert(images.every(image => image.width > 0), 'A service image failed to decode');
  await page.setViewportSize({ width:390, height:844 });
  await page.reload({ waitUntil:'networkidle' });
  await scroll(650);
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'Mobile has horizontal overflow');
  await page.screenshot({ path:'scripts/castas-motion-mobile.jpg', quality:85 });
  const mobileService = page.locator('#services [data-framer-name="Content"]').filter({ visible:true }).first();
  assert(await mobileService.evaluate(el => getComputedStyle(el).transform) === 'none', 'Mobile services should retain their stacked layout');
  await page.emulateMedia({ reducedMotion:'reduce' });
  await scroll(700);
  assert(await entry.evaluate(el => getComputedStyle(el).transform) === 'none', 'Reduced motion is ignored');
  assert(errors.length === 0, errors.join('\n'));
  console.log('Hero hover, entry steps, progressive/reversible services, image decoding, mobile and reduced motion passed.');
} finally { await browser.close(); }
